/// Convert a platform code to its internal key, or return `None`.
#[must_use]
pub fn from_code(code: u32) -> Option<VirtualKey> {
    MAPPING
        .iter()
        .find(|(value, _)| *value == code)
        .map(|(_, key)| *key)
}
